CREATE TABLE app_user (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, account VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
 password_hash VARCHAR(100) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 must_change_password BOOLEAN NOT NULL DEFAULT TRUE, session_version INT NOT NULL DEFAULT 0,
 failed_attempts INT NOT NULL DEFAULT 0, locked_until TIMESTAMP NULL, totp_secret VARCHAR(512) NULL,
 totp_last_step BIGINT NOT NULL DEFAULT -1, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE user_scope (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, role VARCHAR(40) NOT NULL,
 company_id INT NULL, dept_id INT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT fk_scope_user FOREIGN KEY(user_id) REFERENCES app_user(id),
 CONSTRAINT ck_scope_role CHECK(role IN ('GROUP_LEADER','DIVISION_LEADER','COMPANY_LEADER','DEPT_HEAD','EMPLOYEE','ADMIN'))
);
CREATE TABLE recovery_code (id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,code_hash VARCHAR(100) NOT NULL,used_at TIMESTAMP NULL,FOREIGN KEY(user_id) REFERENCES app_user(id));
CREATE TABLE business_record (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, kind VARCHAR(40) NOT NULL, company_id INT NOT NULL,
 dept_id INT NULL, task_id BIGINT NULL, owner_id BIGINT NULL, status VARCHAR(40) NOT NULL,
 version INT NOT NULL DEFAULT 0, payload LONGTEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_record_scope ON business_record(kind,company_id,dept_id,status);
CREATE INDEX ix_record_parent ON business_record(task_id,kind);
CREATE TABLE idempotency_record (
 user_id BIGINT NOT NULL, request_key VARCHAR(36) NOT NULL, request_hash VARCHAR(64) NOT NULL,
 response_json LONGTEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,request_key)
);
CREATE TABLE audit_event (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor_id BIGINT NOT NULL,company_id INT NOT NULL,
 action VARCHAR(100) NOT NULL, object_id BIGINT NOT NULL, trace_id VARCHAR(36) NOT NULL,
 previous_hash VARCHAR(64) NOT NULL, event_hash VARCHAR(64) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE notification_outbox (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,event_key VARCHAR(180) NOT NULL UNIQUE,company_id INT NOT NULL,
 recipient_id BIGINT NOT NULL,task_id BIGINT NULL,title VARCHAR(300) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',attempts INT NOT NULL DEFAULT 0,
 next_attempt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,last_error VARCHAR(100) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE notification (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,outbox_id BIGINT NOT NULL UNIQUE,user_id BIGINT NOT NULL,
 company_id INT NOT NULL,task_id BIGINT NULL,title VARCHAR(300) NOT NULL,is_read BOOLEAN NOT NULL DEFAULT FALSE,
 archived BOOLEAN NOT NULL DEFAULT FALSE,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE job_execution (
 execution_key VARCHAR(180) PRIMARY KEY,status VARCHAR(20) NOT NULL,attempts INT NOT NULL DEFAULT 0,
 started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,finished_at TIMESTAMP NULL,error_code VARCHAR(100) NULL
);
CREATE TABLE kpi_run_key (
 company_id INT NOT NULL, period VARCHAR(7) NOT NULL,template_id BIGINT NOT NULL,run_id BIGINT NOT NULL,
 PRIMARY KEY(company_id,period,template_id)
);
